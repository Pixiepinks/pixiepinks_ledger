"""Private, durable TTS assets and separately fenced manual delivery."""
from datetime import datetime
from sqlalchemy import Column,Integer,String,Text,JSON,DateTime,LargeBinary,Numeric,Float,Boolean,ForeignKey,UniqueConstraint
from database import Base
class MonaraPolicy(Base):
    __tablename__='monara_policy'
    id=Column(Integer,primary_key=True)
    version=Column(Integer,nullable=False,default=1)
    data=Column(JSON,nullable=False,default=dict)
class MonaraJob(Base):
    __tablename__='monara_jobs'
    id=Column(String(36),primary_key=True)
    request_key=Column(String(100),nullable=False,unique=True)
    fingerprint=Column(String(64),nullable=False)
    staff_id=Column(Integer,ForeignKey('users.id'),nullable=False,index=True)
    conversation_id=Column(Integer,ForeignKey('whatsapp_conversations.id'),nullable=False,index=True)
    recipient_hash=Column(String(64),nullable=False)
    status=Column(String(24),nullable=False,index=True)
    transcript=Column(Text,nullable=False)
    language=Column(String(8),nullable=False)
    style=Column(String(40),nullable=False,default='transcript_only')
    style_prompt=Column(Text,nullable=False,default='')
    model=Column(String(100),nullable=False)
    voice=Column(String(100),nullable=False)
    api_version=Column(String(30),nullable=False)
    characters=Column(Integer,nullable=False)
    estimated_cost=Column(Numeric(14,6))
    reserved_cost=Column(Numeric(14,6))
    usage=Column(JSON,nullable=False,default=dict)
    duration=Column(Float)
    mp3=Column(LargeBinary)
    ogg=Column(LargeBinary)
    sha256=Column(String(64))
    shared=Column(Boolean,nullable=False,default=False,index=True)
    active=Column(Boolean,nullable=False,default=True)
    title=Column(String(100))
    category=Column(String(80))
    failure=Column(String(50))
    created_at=Column(DateTime,nullable=False,default=datetime.utcnow,index=True)
    started_at=Column(DateTime)
    completed_at=Column(DateTime)
    expires_at=Column(DateTime,nullable=False,index=True)
class MonaraSend(Base):
    __tablename__='monara_sends'
    id=Column(String(36),primary_key=True)
    request_key=Column(String(100),nullable=False,unique=True)
    job_id=Column(String(36),ForeignKey('monara_jobs.id'),nullable=False,index=True)
    fingerprint=Column(String(64),nullable=False)
    conversation_id=Column(Integer,ForeignKey('whatsapp_conversations.id'),nullable=False,index=True)
    staff_id=Column(Integer,ForeignKey('users.id'),nullable=False)
    recipient_hash=Column(String(64),nullable=False)
    status=Column(String(24),nullable=False,index=True)
    media_id=Column(String(255))
    whatsapp_message_id=Column(String(255),index=True)
    message_id=Column(Integer,ForeignKey('whatsapp_conversation_messages.id'))
    created_at=Column(DateTime,nullable=False,default=datetime.utcnow)
    updated_at=Column(DateTime,nullable=False,default=datetime.utcnow)
    __table_args__=(UniqueConstraint('job_id','conversation_id',name='uq_monara_original_delivery'),)
class MonaraEvent(Base):
    __tablename__='monara_events'
    id=Column(Integer,primary_key=True)
    staff_id=Column(Integer,ForeignKey('users.id'),nullable=False)
    job_id=Column(String(36),ForeignKey('monara_jobs.id'),index=True)
    action=Column(String(50),nullable=False,index=True)
    detail=Column(JSON,nullable=False,default=dict)
    created_at=Column(DateTime,nullable=False,default=datetime.utcnow)
